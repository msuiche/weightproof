fn code(log_n: u32, ell: u64, r: u64) -> CodeSize {
    CodeSize {
        log_n,
        ell,
        r,
        over_E: true,
    }
}
fn shape(
    code: u32,
    main_rows: u64,
    main_deg: u32,
    mask_rows: u64,
    mask_code: u32,
    answers: u32,
) -> OracleShape {
    OracleShape {
        code,
        main_rows,
        main_deg,
        mask_rows,
        mask_code,
        answers,
    }
}
fn stage(code: u32, mask_code: u32, k: u32, h: u32) -> IoppStage {
    IoppStage {
        code,
        mask_code,
        k,
        h,
    }
}

